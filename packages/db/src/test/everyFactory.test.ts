import { afterAll, afterEach, describe, expect, it } from 'bun:test';
import { faker } from '@faker-js/faker';
import { fieldOf, relationsOf, uniqueKeysOf } from '@inixiative/field-map';
import { db } from '@template/db/client';
import { prismaMap } from '@template/db/generated/prismaMap';
import {
  columnDefaultOf,
  discriminatorRequiresValue,
  withDiscriminatorDefaults,
} from '@template/db/registries/discriminatorDefaults';
import { polymorphismConfigForModel } from '@template/db/registries/falsePolymorphism';
import { cleanupTouchedTables } from '@template/db/test';
import * as factories from '@template/db/test/factories';
import {
  nextFactorySequenceNumber,
  registeredDefaults,
  registeredDependencies,
  resetSequence,
} from '@template/db/test/factory';
import type { ModelName } from '@template/db/test/factoryTypes';
import { modelNames } from '@template/db/utils/modelNames';

type CreateWithDefaults = () => Promise<{ entity: { id: string } }>;

const creators = Object.entries(factories).flatMap(([name, value]) =>
  name.startsWith('create') && typeof value === 'function'
    ? [[name, value as unknown as CreateWithDefaults] as const]
    : [],
);

const requiresDiscriminator = (modelName: ModelName, seen = new Set<ModelName>()): boolean => {
  if (seen.has(modelName)) return false;
  seen.add(modelName);
  if (
    polymorphismConfigForModel(modelName)?.axes.some((axis) =>
      discriminatorRequiresValue(modelName, axis.field),
    )
  )
    return true;
  return Object.values(registeredDependencies(modelName)).some(
    (dependency) => dependency.required && requiresDiscriminator(dependency.modelName, seen),
  );
};

describe('every model', () => {
  it('has a factory', () => {
    const modelsWithFactory = new Set(creators.map(([name]) => name.slice('create'.length)));
    expect(modelNames.filter((modelName) => !modelsWithFactory.has(modelName))).toEqual([]);
  });
});

describe('every factory against the polymorphism registry', () => {
  afterEach(async () => {
    await cleanupTouchedTables(db);
  });

  for (const [name, create] of creators) {
    const modelName = name.slice('create'.length) as ModelName;
    if (requiresDiscriminator(modelName))
      it(`${name} refuses to choose a discriminator for the caller`, async () => {
        await expect(create()).rejects.toThrow('is required — pass it');
      });
    else
      it(`${name} persists a row with its defaults`, async () => {
        const { entity } = await create();
        expect(entity.id).toBeString();
      });
  }
});

const UUID = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i;

const foreignKeysOf = (modelName: ModelName): Set<string> =>
  new Set(
    relationsOf(prismaMap, modelName).flatMap(({ foreignKey }) =>
      foreignKey === null
        ? []
        : typeof foreignKey === 'string'
          ? [foreignKey]
          : Object.values(foreignKey),
    ),
  );

const uniqueKeysWithoutForeignKeysOf = (modelName: ModelName): string[][] => {
  const foreignKeys = foreignKeysOf(modelName);
  return uniqueKeysOf(prismaMap, modelName).map((key) =>
    key.filter((field) => !foreignKeys.has(field)),
  );
};

const GENERATED_BY_THE_DATABASE = Symbol('generated by the database');
const PASSED_BY_THE_CALLER = Symbol('passed by the caller');

const valueAsCreated = (
  modelName: ModelName,
  row: Record<string, unknown>,
  field: string,
): unknown => {
  if (row[field] !== undefined) return row[field];
  const columnDefault = columnDefaultOf(modelName, field);
  if (columnDefault?.kind === 'literal') return columnDefault.value;
  if (columnDefault?.kind === 'generated') return GENERATED_BY_THE_DATABASE;
  return fieldOf(prismaMap, modelName, field)?.isRequired ? PASSED_BY_THE_CALLER : null;
};

const SEEDS = Array.from({ length: 32 }, (_, index) => index + 1);

const defaultsAt = (
  modelName: ModelName,
  defaults: () => unknown,
  { step, seed }: { step: number; seed: number },
): Record<string, unknown> => {
  resetSequence();
  for (let i = 0; i < step; i++) nextFactorySequenceNumber();
  faker.seed(seed);
  return withDiscriminatorDefaults(modelName, defaults() as Record<string, unknown>);
};

const keyValue = (modelName: ModelName, row: Record<string, unknown>, key: string[]) =>
  key.map((field) => String(valueAsCreated(modelName, row, field))).join('\u0000');

const collidingKeys = (): string[] =>
  modelNames
    .flatMap((modelName) => {
      const defaults = registeredDefaults(modelName);
      if (!defaults) return [];
      const [first, ...otherSeeds] = SEEDS.map((seed) =>
        defaultsAt(modelName, defaults, { step: 0, seed }),
      );
      const replay = defaultsAt(modelName, defaults, { step: 0, seed: SEEDS[0] });
      const nextStep = defaultsAt(modelName, defaults, { step: 1, seed: SEEDS[0] });
      const asCreated = (row: Record<string, unknown>, field: string) =>
        valueAsCreated(modelName, row, field);
      return uniqueKeysWithoutForeignKeysOf(modelName)
        .filter((key) => key.length && key.every((field) => asCreated(first, field) != null))
        .filter(
          (key) => !key.some((field) => asCreated(first, field) === GENERATED_BY_THE_DATABASE),
        )
        .filter((key) => !key.some((field) => UUID.test(String(asCreated(first, field)))))
        .filter((key) => {
          const value = keyValue(modelName, first, key);
          const isOutsideFaker = value !== keyValue(modelName, replay, key);
          const isFromFaker = otherSeeds.some((row) => keyValue(modelName, row, key) !== value);
          const isFromSequence = value !== keyValue(modelName, nextStep, key);
          return isOutsideFaker || (isFromFaker && !isFromSequence);
        })
        .map((key) => `${modelName}.${key.join('+')}`);
    })
    .filter((key, index, keys) => keys.indexOf(key) === index);

describe('every factory against the unique keys', () => {
  const resumeAt = nextFactorySequenceNumber();

  afterAll(() => {
    faker.seed();
    resetSequence();
    while (nextFactorySequenceNumber() < resumeAt);
  });

  it('every unique key a factory fills changes with the sequence, so two rows in one test cannot collide', () => {
    expect(collidingKeys()).toEqual([]);
  });

  it("a part the defaults leave out takes the value a created row has: the column default, the caller's value when required, otherwise NULL", () => {
    const webhookDefaults = registeredDefaults('WebhookSubscription')?.() as Record<
      string,
      unknown
    >;
    expect(valueAsCreated('WebhookSubscription', webhookDefaults, 'resourceModel')).toBe(
      PASSED_BY_THE_CALLER,
    );
    expect(valueAsCreated('WebhookSubscription', webhookDefaults, 'isActive')).toBe(true);
    expect(valueAsCreated('WebhookSubscription', {}, 'id')).toBe(GENERATED_BY_THE_DATABASE);
    expect(valueAsCreated('JobOutbox', {}, 'dedupeKey')).toBeNull();
  });

  it('the check sees field-level and composite unique keys, so it cannot pass by finding none', () => {
    expect(uniqueKeysWithoutForeignKeysOf('User')).toContainEqual(['email']);
    expect(
      modelNames
        .flatMap((modelName) => uniqueKeysWithoutForeignKeysOf(modelName))
        .some((key) => key.length > 1),
    ).toBe(true);
  });
});
